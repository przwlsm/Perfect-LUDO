/// <reference types="node" />
// Builds every level from its seed and writes src/application/levels/shipped.ts.
// Run with `npm run levels` (it runs through Jest, which already compiles the
// app's TypeScript). The shipped file is what players get; tests check that
// it still matches what the seeds build, so levels never change by accident.
import fs from 'node:fs';
import path from 'node:path';
import { freshLevel, LEVEL_COUNT } from '../src/application/levels/levels';

it('builds every level', () => {
  const lines: string[] = [];
  const started = Date.now();
  for (let n = 1; n <= LEVEL_COUNT; n++) {
    lines.push(freshLevel(n));
    if (n % 20 === 0) console.log(`level ${n}: ${((Date.now() - started) / 1000).toFixed(0)} s`);
  }
  const body = lines.map((l) => `  ${JSON.stringify(l)},`).join('\n');
  const file = `// Generated by \`npm run levels\` from each level's seed. Do not edit by hand.\n// prettier-ignore\nexport const SHIPPED: readonly string[] = [\n${body}\n];\n`;
  fs.writeFileSync(path.join(__dirname, '../src/application/levels/shipped.ts'), file);
  console.log(`Built ${LEVEL_COUNT} levels in ${((Date.now() - started) / 1000).toFixed(1)} s`);
}, 3_600_000);
