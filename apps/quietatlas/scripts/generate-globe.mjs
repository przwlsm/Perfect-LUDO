// Builds the globe's land dots from Natural Earth's 1:110m land polygons
// (public domain, via the world-atlas package). Points are spread evenly over
// the sphere (a Fibonacci lattice) and kept where they fall on land.
// Run with `npm run globe`; writes src/presentation/globe/landDots.ts.
import fs from 'node:fs/promises';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const topology = require('world-atlas/land-110m.json');
const land = feature(topology, topology.objects.land);

/** Number of lattice points over the whole sphere; about 29% land on. */
const LATTICE = 5200;

/** Ray-casting point-in-ring test in lon/lat degrees. */
function inRing(ring, lon, lat) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
function inPolygon(rings, lon, lat) {
  if (!inRing(rings[0], lon, lat)) return false;
  for (let k = 1; k < rings.length; k++) if (inRing(rings[k], lon, lat)) return false;
  return true;
}
const polygons = land.features.flatMap((f) =>
  f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates,
);
const onLand = (lon, lat) => polygons.some((rings) => inPolygon(rings, lon, lat));

const golden = Math.PI * (3 - Math.sqrt(5));
const dots = [];
for (let i = 0; i < LATTICE; i++) {
  const y = 1 - (2 * (i + 0.5)) / LATTICE;
  const lat = (Math.asin(y) * 180) / Math.PI;
  let lon = ((i * golden * 180) / Math.PI) % 360;
  if (lon > 180) lon -= 360;
  // Antarctica is a wide white band from this distance; leave the pole clear.
  if (lat < -62) continue;
  if (onLand(lon, lat)) dots.push(Math.round(lat * 10) / 10, Math.round(lon * 10) / 10);
}

const body = `// Generated by scripts/generate-globe.mjs from Natural Earth (public domain). Do not edit.
// Flat [lat, lon, lat, lon, …] in degrees: ${dots.length / 2} land dots.
export const LAND_DOTS: readonly number[] = [${dots.join(',')}];
`;
const target = new URL('../src/presentation/globe/landDots.ts', import.meta.url);
await fs.mkdir(new URL('.', target), { recursive: true });
await fs.writeFile(target, body);
console.log(`Wrote ${dots.length / 2} land dots.`);
