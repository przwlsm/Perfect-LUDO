export function isOccasionId(id: unknown): id is OccasionId {
  return typeof id === 'string' && (OCCASION_IDS as readonly string[]).includes(id);
}

export function occasionById(id: OccasionId): Occasion {
  return OCCASIONS.find((o) => o.id === id)!;
}
