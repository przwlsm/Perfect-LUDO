/// <reference types="node" />
// Builds every level from its seed and writes src/application/levels/shipped.ts.
// Run with `npm run levels` (it runs through Jest, which already compiles the
// app's TypeScript). The shipped file is what players get; a test checks it
// still matches what the seeds build, so levels never change by accident.
// It also reports which levels the solver proved to have exactly one answer.
import fs from 'node:fs';
import path from 'node:path';
import { solve } from '../src/application/engine/solver';
import { encodeLevel } from '../src/application/levels/codec';
import { freshLevel, LEVEL_COUNT } from '../src/application/levels/levels';

it('builds every level', () => {
  const lines: string[] = [];
  const notUnique: number[] = [];
  const started = Date.now();
  for (let n = 1; n <= LEVEL_COUNT; n++) {
    const level = freshLevel(n);
    const r = solve(level, { limit: 2 });
    if (!(r.complete && r.solutions.length === 1)) notUnique.push(n);
    lines.push(encodeLevel(level));
  }
  const body = lines.map((l) => `  ${JSON.stringify(l)},`).join('\n');
  const file = `// Generated by \`npm run levels\` from each level's seed. Do not edit by hand.\n// prettier-ignore\nexport const SHIPPED: readonly string[] = [\n${body}\n];\n`;
  fs.writeFileSync(path.join(__dirname, '../src/application/levels/shipped.ts'), file);
  console.log(
    `Built ${LEVEL_COUNT} levels in ${((Date.now() - started) / 1000).toFixed(1)} s. ` +
      `Not unique: ${notUnique.length ? notUnique.join(', ') : 'none'}.`,
  );
});
